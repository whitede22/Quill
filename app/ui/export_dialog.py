"""导出格式对话框，以及「格式说明」只读对话框。

## 为什么需要一个「先选格式」的对话框

在此之前，导出只有一条路：文件保存框里挂着 `文本文件 (*.txt);;Markdown (*.md)`。
于是**按钮写着「导出文本」，保存框里却藏着 Markdown**——用户不点开那个下拉框
就不知道能出 .md，而按钮名还在告诉他只有文本。

这一轮的取舍是「一键直出」换「先问一句」：格式多了之后，用一个下拉框来选
很容易被忽略（默认值会被当成唯一选项），把每种格式**摆出来并写清用途**，
用户才真的在做选择。

## 为什么「格式说明」的样例必须现算

说明里要展示「导出后长什么样」。若把样例写成文档里的死字符串，格式一改，
说明就开始骗人——而它骗的恰恰是「不知道该怎么选」的那部分用户。
所以样例一律调真正的导出函数现算（见 `format_samples()`）。
"""

from __future__ import annotations

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QCheckBox,
    QDialog,
    QDialogButtonBox,
    QLabel,
    QPlainTextEdit,
    QRadioButton,
    QVBoxLayout,
)

from ..core.exporter import (
    export_anki,
    export_csv,
    export_json,
    export_markdown,
    export_text,
    export_wordlist,
)
from ..core.models import Collocation, Entry, Synonym

# 每种导出格式：键、显示名、一句话用途、扩展名。
# 顺序即界面顺序，**第一条是默认项**（最通用的纯文本）。
EXPORT_FORMATS: tuple[tuple[str, str, str, str], ...] = (
    ("text", "纯文本 (.txt)", "打印用。保留备注里的换行与行首符号，不转义。", ".txt"),
    (
        "wordlist",
        "单词表 (.txt)",
        "只有单词与中文释义两列，一行一条。软件更新或换机器后可以整份导回来。",
        ".txt",
    ),
    ("markdown", "Markdown (.md)", "粘进笔记软件或继续转排版。会转义备注里的符号。", ".md"),
    ("pdf", "PDF (.pdf)", "直接交出去或打印。中文嵌入字体，可搜索可复制。", ".pdf"),
    ("csv", "表格 (.csv)", "用 Excel/WPS 打开筛选排序。同义语与固定搭配各压在一格里，有损。", ".csv"),
    (
        "anki",
        "Anki 卡片 (.txt)",
        "导入 Anki 背。制表符分三列：正面 / 背面 / 标签，音标、例句与固定搭配折进背面。",
        ".txt",
    ),
    ("json", "JSON (.json)", "给程序读或做备份。带格式标识与版本号，可被本程序读回。", ".json"),
)

# 格式说明里展示样例时用的**假数据**。刻意用一个字段齐全、且包含「会出问题的
# 字符」的词条：逗号、引号、多行备注、带中文简释的同义语。样例里出现这些东西，
# 用户才能看出各格式在「有损」这件事上的差别。
_SAMPLE_ENTRIES = [
    Entry(
        lemma="ubiquitous",
        phonetic="/juːˈbɪkwɪtəs/",
        pos="adj.",
        definition_en="seeming to be everywhere",
        definition_zh="无处不在的",
        example="Mobile phones are ubiquitous.",
        example_zh="手机无处不在。",
        synonyms=[Synonym(word="pervasive", gloss_zh="弥漫的", diff_note="更强调渗透")],
        collocations=[
            Collocation(
                phrase="become ubiquitous",
                gloss_zh="变得无处不在",
                example="Plastic bags have become ubiquitous.",
                example_zh="塑料袋已变得无处不在。",
            )
        ],
        notes="记忆法：ubi=where\n第二行备注",
        tags="考研 高频",
    ),
]


def format_samples() -> dict[str, str]:
    """现算每种格式的样例文本。

    单独提出来是为了能被测试直接调用——「说明里的样例与真实导出一致」这件事
    必须可验证，否则它迟早会变成一段过期的说明文字。
    """
    samples: dict[str, str] = {}
    for key, _label, _hint, _ext in EXPORT_FORMATS:
        if key == "text":
            samples[key] = export_text(_SAMPLE_ENTRIES, "英语生词本")
        elif key == "wordlist":
            samples[key] = export_wordlist(_SAMPLE_ENTRIES, "英语生词本")
        elif key == "markdown":
            samples[key] = export_markdown(_SAMPLE_ENTRIES, "英语生词本")
        elif key == "csv":
            samples[key] = export_csv(_SAMPLE_ENTRIES, "英语生词本")
        elif key == "anki":
            samples[key] = export_anki(_SAMPLE_ENTRIES, "英语生词本")
        elif key == "json":
            samples[key] = export_json(_SAMPLE_ENTRIES, "英语生词本")
        else:
            # PDF 是二进制产物，没有可展示的文本形态，改用版式描述。
            samples[key] = (
                "（PDF 是排版产物，这里显示它的版式说明）\n\n"
                "英语生词本\n"
                "导出时间 2026-01-01 09:00　共 1 条\n"
                "Generated by Quill\n"
                "\n"
                "1. ubiquitous  /juːˈbɪkwɪtəs/  adj.\n"
                "英　seeming to be everywhere\n"
                "中　无处不在的\n"
                "例　Mobile phones are ubiquitous.\n"
                "　　手机无处不在。\n"
                "同　pervasive（弥漫的） — 更强调渗透\n"
                "搭　become ubiquitous（变得无处不在）\n"
                "　　　Plastic bags have become ubiquitous.\n"
                "　　　塑料袋已变得无处不在。\n"
                "注　记忆法：ubi=where\n"
                "　　第二行备注\n"
                "\n"
                "— 词条之间用一条细横线分隔；中文嵌入字体，可搜索可复制。"
            )
    return samples


class ExportDialog(QDialog):
    """选导出格式与范围。属性 `format_key` / `unlimited` 是选择结果。"""

    def __init__(self, total: int, filtered: bool, parent=None) -> None:
        super().__init__(parent)
        self.setWindowTitle("导出")
        self.setMinimumWidth(430)

        layout = QVBoxLayout(self)
        layout.setSpacing(8)

        head = QLabel("导出成什么格式？")
        head.setObjectName("sectionTitle")
        layout.addWidget(head)

        self._buttons: dict[str, QRadioButton] = {}
        for key, label, hint, _ext in EXPORT_FORMATS:
            radio = QRadioButton(label)
            radio.setToolTip(hint)
            layout.addWidget(radio)
            # 用途说明紧跟在选项下面，缩进对齐。悬停提示容易被错过，而
            # 「选哪个」正是这个对话框唯一要解决的问题。
            note = QLabel(f"　　{hint}")
            note.setObjectName("formatHint")
            note.setWordWrap(True)
            layout.addWidget(note)
            self._buttons[key] = radio

        self._buttons[EXPORT_FORMATS[0][0]].setChecked(True)

        layout.addSpacing(6)
        scope_head = QLabel("导出哪些词条？")
        scope_head.setObjectName("sectionTitle")
        layout.addWidget(scope_head)

        self.scope_all = QRadioButton(f"全部（{total} 条）")
        self.scope_limited = QRadioButton("跟随当前筛选")
        self.scope_all.setChecked(True)
        layout.addWidget(self.scope_all)
        # 筛选不生效时把它置灰，而不是让用户勾一个没用的选项——
        # 「勾了没用」等同虚假选项。
        layout.addWidget(self.scope_limited)
        if not filtered:
            self.scope_limited.setEnabled(False)
            self.scope_limited.setText("跟随当前筛选（当前没有筛选）")

        layout.addSpacing(6)
        self.unlimited_check = QCheckBox("不受列表显示上限约束（推荐）")
        self.unlimited_check.setChecked(True)
        self.unlimited_check.setToolTip(
            "列表为流畅只显示前若干条；导出默认取全部，避免打印稿少掉一截。"
        )
        layout.addWidget(self.unlimited_check)

        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Ok | QDialogButtonBox.StandardButton.Cancel
        )
        buttons.button(QDialogButtonBox.StandardButton.Ok).setText("导出")
        buttons.button(QDialogButtonBox.StandardButton.Cancel).setText("取消")
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        layout.addWidget(buttons)

    @property
    def format_key(self) -> str:
        for key, radio in self._buttons.items():
            if radio.isChecked():
                return key
        return EXPORT_FORMATS[0][0]

    @property
    def unlimited(self) -> bool:
        return self.unlimited_check.isChecked()

    @property
    def filtered_only(self) -> bool:
        return self.scope_limited.isChecked()


class FormatHelpDialog(QDialog):
    """只读的「格式说明」：把每种格式和它的真实样例摆出来。

    这件事本来也可以写进 README，但用户是在**正要导出的时候**不知道选哪个，
    那一刻他不会去翻文档。放在对话框里，他不必离开当前这一屏。
    """

    def __init__(self, parent=None) -> None:
        super().__init__(parent)
        self.setWindowTitle("导出格式说明")
        self.resize(640, 560)

        layout = QVBoxLayout(self)
        layout.setSpacing(8)

        samples = format_samples()
        for key, label, hint, ext in EXPORT_FORMATS:
            title = QLabel(label)
            title.setObjectName("sectionTitle")
            layout.addWidget(title)

            desc = QLabel(f"{hint}\n扩展名默认 {ext}")
            desc.setObjectName("formatHint")
            desc.setWordWrap(True)
            layout.addWidget(desc)

            box = QPlainTextEdit()
            box.setReadOnly(True)
            box.setPlainText(samples[key])
            box.setMaximumHeight(120)
            # 样例里会出现一个 BOM（U+FEFF）。它是导出产物真实的一部分，但显示
            # 成零宽字符会让人以为「这里怎么好像有个空格」。说明里点一句，
            # 免得有人以为是 bug。
            if key == "csv":
                box.setToolTip("注意：文件开头有一个不可见的 BOM，用来让 Excel 正确识别编码。")
            elif key == "wordlist":
                box.setToolTip(
                    "两列之间是一个制表符，在这里显示为一段空白。"
                    "这份文件没有任何标题或表尾——多一行非词条的内容，"
                    "重新导入时就会多一条「没认出单词」。"
                )
            elif key == "anki":
                box.setToolTip(
                    "制表符在样例里显示为一段空白——每一行都是「正面 → 背面 → 标签」三列。"
                )
            layout.addWidget(box)

        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        buttons.button(QDialogButtonBox.StandardButton.Close).setText("关闭")
        buttons.rejected.connect(self.reject)
        layout.addWidget(buttons)
