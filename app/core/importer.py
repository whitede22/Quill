# `.docm` 与 `.docx` 同为 OOXML 包（只是多带宏，宏不会被读），因此一并认。
# 老式的二进制 `.doc` **不在其内**：它不是 zip，只能请用户另存为 .docx。
_DOCX_SUFFIXES = frozenset({".docx", ".docm"})

# WordprocessingML 的名字空间。取值一律用完整 QName（`{ns}p`）而不是本地名：
# 本地名会把别的名字空间里同名的 `p`（段落 / 属性 / …）一起吞进来。
_W_NS = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def read_import_text(path: Path | str) -> str:
    """把导入文件读成纯文本：`.docx` 解包，其余按文本读。

    **这是导入侧唯一的入口**，`main_window` 不该自己判后缀——判据散在两处
    （对话框认一份、读取认一份）时，改了一处就会出现「选得到、读不了」。
    """
    path = Path(path)
    if path.suffix.lower() in _DOCX_SUFFIXES:
        return read_docx_text(path)
    return read_text_file(path)


def read_docx_text(path: Path | str) -> str:
    """把 `.docx` 的正文读成纯文本，**一行 = 一个段落**。

    为什么不用第三方库：`.docx` 本就是一个 zip，正文在 `word/document.xml`，
    标准库 `zipfile` + `xml.etree` 足够——而多一个依赖就多一处打包与裁剪风险。

    两条容易踩的规矩：

    1. **只读 `word/document.xml`**。页眉、页脚、脚注都是同目录下的其它 part，
       一起读进来会让页眉上的公司名变成「生词」。
    2. **压缩包大小说明不了解压后的体积**。几十 KB 的 zip 能解出几 GB 的 XML，
       所以 zip 内那一条的文件大小也要单独把关。

    读不动一律抛 `ValueError`（与 `read_text_file` 一致），由调用方译成中文提示：
    用户拿到的是「老式 .doc 请另存为 .docx」，而不是一个 traceback。
    """
    path = Path(path)
    try:
        size = path.stat().st_size
    except OSError as exc:
        raise ValueError(f"读不出这个文件（{exc}）") from exc
    if size > MAX_FILE_BYTES:
        raise ValueError(
            f"文件过大（{size / 1024 / 1024:.1f} MB）。生词表通常只有几十 KB，"
            "请确认选对了文件。"
        )

    try:
        with zipfile.ZipFile(path) as archive:
            info = archive.getinfo("word/document.xml")
            if info.file_size > MAX_FILE_BYTES:
                raise ValueError("文档正文过大，这不像是一份生词表。")
            payload = archive.read(info)
    except zipfile.BadZipFile as exc:
        raise ValueError(
            "这不是 .docx 文档。老式的 .doc 请在 Word 里另存为 .docx 后再导入。"
        ) from exc
    except KeyError as exc:
        raise ValueError("这个文件里没有正文，不像是 Word 文档。") from exc
    except OSError as exc:
        raise ValueError(f"读不出这个文件（{exc}）") from exc

    try:
        root = ET.fromstring(payload)
    except ET.ParseError as exc:
        raise ValueError(f"文档内容解析失败（{exc}）") from exc

    return "\n".join(_docx_paragraph(para) for para in root.iter(f"{_W_NS}p"))


def _docx_paragraph(para) -> str:
    """拼出一个段落的文字：`w:t` 取字，`w:tab` / `w:br` 还原成制表与换行。

    只取 `w:t` 是不够的：`<w:tab/>` 与 `<w:br/>` 都是**空元素、没有文本**，
    两列之间不留任何东西会粘成一个词（`apple苹果`），随后被「第一个汉字之后
    都是解释」的规则整段切掉——用户拿到的是一个词都不剩。
    """
    parts: list[str] = []
    for node in para.iter():
        if node.tag == f"{_W_NS}t":
            parts.append(node.text or "")
        elif node.tag == f"{_W_NS}tab":
            parts.append("\t")
        elif node.tag in (f"{_W_NS}br", f"{_W_NS}cr"):
            parts.append("\n")
    return "".join(parts)


# ---------- 解析分派 ----------


def parse_text(text: str) -> ParseResult:
    """按文件指纹选择解析器。

    顺序有讲究：JSON 与 XML 必须排在最前。它们各自带**结构**（顶层对象带格式
    标识 / 根元素名），指纹最严；后两个是「像就认」的启发式——一旦让它们先看，
    JSON 里的 `"lemma"`、XML 里的 `<word>` `<trans>` 这些行就会先被当成词收走。
    """
    if _looks_like_json_export(text):
        return _parse_json_export(text)
    if _looks_like_xml_export(text):
        return _parse_xml_export(text)
    if _looks_like_text_export(text):
        return _parse_text_export(text)
    if _looks_like_markdown_export(text):
        return _parse_markdown_export(text)
    return parse_word_list(text)


# ---------- 解析：有道单词本的 XML ----------


def _xml_local_name(tag: object) -> str:
    """取元素的本地名：剥掉 `{命名空间}` 前缀并小写化。

    小写化是为了容忍手工编辑过的文件（`<WORD>` / `<Item>`）。有道的导出固定用
    小写，但用户完全可能照着别处的模板自己拼一份出来。
    """
    name = str(tag or "")
    if "}" in name:
        name = name.rsplit("}", 1)[-1]
    return name.strip().lower()


def _xml_child(elem, name: str):
    """在直接子元素里找本地名匹配的第一个；找不到返回 None。"""
    for child in elem:
        if _xml_local_name(child.tag) == name:
            return child
    return None


def _xml_text(elem, name: str) -> str:
    """取子元素的文本并折叠空白。

    `ElementTree` 会把 `<![CDATA[…]]>` 的内容当普通文本交给 `text`，所以这里
    不需要为 CDATA 写特例。折叠空白与导出侧对「机器生成的单值字段」的处理一致
    （见 exporter 模块开头）：释义内部的换行只可能是排版噪音。
    """
    child = _xml_child(elem, name)
    if child is None:
        return ""
    return " ".join((child.text or "").split())


def _xml_definition(trans: str) -> dict:
    """把有道的 `<trans>` 放进对应的释义字段。

    有道不区分中英释义，`<trans>` 里混着词性标记与解释（`vt. 放弃，抛弃`）。
    判据用**有没有汉字**：有汉字说明这是给中文用户看的释义，归中文释义字段；
    整段没有汉字（纯英文解释）才归英文释义字段。

    刻意**不把 `vt.` 这类词性标记剥出来放进 `pos`**：那会改掉用户看到的原文，
    而同一位置还可能是 `abbr.`、`（口）` 这类非标准写法，剥下来未必是合法的
    词性标注。宁可原样保留，让释义自己说清楚。
    """
    if not trans:
        return {}
    if _CJK_RE.search(trans):
        return {"definition_zh": trans}
    return {"definition_en": trans}


def _looks_like_xml_export(text: str) -> bool:
    """认出有道单词本导出的 XML。

    **必须三重条件同时满足**，缺一不可：

    1. 去掉前导空白后以 `<` 开头 —— 快速排除绝大多数文本；
    2. `ET.fromstring` 能解析 —— 排除 HTML、以及被截断的文件；
    3. 根元素的**本地名**是 `wordbook` —— 这一步最关键。只验「是 XML」是不够的：
       任何 XML 文件都会通过，于是**别人的配置文件也会被当成生词本读进来**，
       而它的标签名同样会被当成单词。那正是这条路径存在的原因。

    解析失败一律返回 False（走后面的启发式），不抛异常：用户可能选到一个
    损坏的文件，那时该给他「没认出单词」的提示，而不是一个 traceback。
    """
    stripped = text.lstrip()
    if not stripped.startswith("<"):
        return False
    try:
        root = ET.fromstring(stripped)
    except (ET.ParseError, ValueError):
        # ValueError 同理：字符串里带了编码声明之类的怪东西，与「解析不了」同义
        return False
    return _xml_local_name(root.tag) in _XML_ROOT_NAMES


def _parse_xml_export(text: str) -> ParseResult:
    """解析有道单词本 XML：取 `item/word` 作词，其余标签作回填字段。

    调用方已保证这份文本能解析出根元素为 `wordbook` 的 XML，所以这里不再重复
    校验（重复校验会让「谁负责判格式」变成两处，改动时容易漏改一处）。

    **必须按结构取字段，不能逐行取词**——这正是这条路径存在的理由：有道的
    标签名（word / trans / phonetic / tags / progress）恰好都是合法英文词，
    逐行取词会把它们全部收进生词本，而真词一个都取不到。

    `line` 记的是**第几条 item**而不是文件行号：XML 里一行能塞下整条词条，
    文件行号对用户没有意义，「第 3 条有问题」才是能照着改的信息。
    """
    root = ET.fromstring(text.lstrip())
    result = ParseResult(
        source_format="有道单词本（XML）",
        total_lines=len(text.splitlines()),
    )
    seen: dict[str, int] = {}

    for index, item in enumerate(root, start=1):
        if _xml_local_name(item.tag) != "item":
            continue
        word = _xml_text(item, "word")
        if not word:
            result.skipped.append((index, "词条缺少 <word> 内容"))
            continue
        fill: dict = {}
        fill.update(_xml_definition(_xml_text(item, "trans")))
        for label, field_name in _XML_FIELD_MAP:
            value = _xml_text(item, label)
            if value:
                fill[field_name] = value
        _collect(result, seen, word, index, "", fill)
    return result


def _looks_like_json_export(text: str) -> bool:
    """认出本程序导出的 JSON。

    **必须三重条件同时满足**，缺一不可：

    1. 去掉前导空白后以 `{` 开头 —— 快速排除绝大多数文本；
    2. `json.loads` 能解析 —— 排除坏文件（用户的文件可能截断了）；
    3. 顶层 `format` 等于我们的标识 —— 这一步最关键。只验「是 JSON」是不够的：
       任何 JSON 文件都会通过，于是**别人的配置文件也会被当成生词本读进来**，
       而它的字段名同样会被当成单词。那正是这条路径存在的原因。

    解析失败一律返回 False（走后面的启发式），不抛异常：用户可能选到一个
    损坏的文件，那时该给他「没认出单词」的提示，而不是一个 traceback。
    """
    stripped = text.lstrip()
    if not stripped.startswith("{"):
        return False
    try:
        payload = json.loads(stripped)
    except (ValueError, TypeError):
        return False
    if not isinstance(payload, dict):
        # 顶层是数组的 JSON 不是本程序的导出（导出的是带元信息的对象）
        return False
    return payload.get("format") == _JSON_FORMAT_TAG


def _parse_json_export(text: str) -> ParseResult:
    """解析本程序导出的 JSON：取出 `entries[].lemma` 与备注。

    调用方已保证这份文本能解析出带格式标识的对象，所以这里不再重复校验
    （重复校验会让「谁负责判格式」变成两处，改动时容易漏改一处）。

    **本轮只收单词与备注，不回填释义等字段。** JSON 里带着完整的释义、例句、
    同义语，但把它们写回库里要改 `run_import` 的写入路径，而那会碰到
    「导入不覆盖用户自有字段」这条既有约定（已有词条的备注不能被覆盖）。
    分两步走：先把格式认对、把词收对，回填单独一轮做，改动面可控。

    即便如此，**备注要带上**：它本来就在导入路径的还原范围内（文本/Markdown
    导出也还原备注），JSON 不带反而是功能倒退。
    """
    payload = json.loads(text.lstrip())
    raw_entries = payload.get("entries")
    if not isinstance(raw_entries, list):
        raw_entries = []

    result = ParseResult(
        source_format="Quill JSON 导出",
        total_lines=len(text.splitlines()),
    )
    seen: dict[str, int] = {}
    for i, item in enumerate(raw_entries, start=1):
        if not isinstance(item, dict):
            continue
        word = str(item.get("lemma") or "").strip()
        if not word:
            result.skipped.append((i, "词条缺少 lemma 字段"))
            continue
        key = normalize(word)
        if key in seen:
            result.duplicates += 1
            continue
        seen[key] = i
        result.words.append(
            ParsedWord(
                word=word,
                line=i,
                notes=str(item.get("notes") or ""),
                fill=_json_fill(item),
            )
        )
    return result


def _json_fill(item: dict) -> dict:
    """从 JSON 词条里取出可回填的字段。

    与有道那条走**同一套白名单**（`_FILLABLE_FIELDS`，由 `run_import` 统一裁决），
    这里只负责把值取出来。`synonyms` 是对象列表，交给 `Synonym.from_raw` 容错
    解析后再放进 fill——它本来就是为「模型返回多种形态」写的，正好复用。

    「JSON 全字段回填」本来是上一轮明确推迟的：当时改写入路径风险大，先只认
    格式、只收单词。现在回填机制已为有道 XML 建好，两条路径共用同一套，就没有
    理由让 JSON 继续缺这一块——**同一件事留两份口径**才是更大的风险。
    """
    fill: dict = {}
    for name in _FILLABLE_FIELDS:
        if name in _NESTED_FILL_FIELDS:
            continue
        value = item.get(name)
        if isinstance(value, str) and value.strip():
            fill[name] = value.strip()
    raw_syns = item.get("synonyms")
    if isinstance(raw_syns, list):
        syns = [s for s in (Synonym.from_raw(x) for x in raw_syns) if s]
        if syns:
            fill["synonyms"] = syns
    # 固定搭配与同义语同款：都是对象列表，都走各自的 from_raw 容错解析。
    # 少了这一段，JSON 导出里的搭配就**读不回来**——而 JSON 一直被当作
    # 「可以安全地在机器之间搬」的那个格式，丢字段正是它最不该发生的事。
    raw_colls = item.get("collocations")
    if isinstance(raw_colls, list):
        colls = [c for c in (Collocation.from_raw(x) for x in raw_colls) if c]
        if colls:
            fill["collocations"] = colls
    return fill


def _looks_like_text_export(text: str) -> bool:
    if _EXPORT_MARK in text:
        return True
    # 用户可能把文件尾的署名行裁掉，所以不能只认那一句。两条线同时出现
    # 才算——普通词表不会恰好有 72 个 `=` 又有 72 个 `-`。
    return bool(_HEAVY_RE.search(text) and _RULE_RE.search(text))


def _looks_like_markdown_export(text: str) -> bool:
    """`## N. 单词` 是导出 Markdown 的词条标题。

    普通笔记里也可能出现 `## 1. 学习方法`，但那种行取不出英文词，解析结果
    是空——判错无害，而漏判会让释义行被当成词条，所以这里也倾向于「像就认」。
    """
    return any(_MD_ENTRY_RE.match(line) for line in text.splitlines())


# ---------- 解析：本程序导出的纯文本 ----------


def _parse_text_export(text: str) -> ParseResult:
    """按 `----` 分隔的词条块解析，只取每块首行的词，并还原备注。"""
    lines = text.splitlines()
    result = ParseResult(source_format="Quill 文本导出", total_lines=len(lines))
    seen: dict[str, int] = {}

    i = 0
    while i < len(lines):
        match = _TXT_ENTRY_RE.match(lines[i])
        if not match:
            i += 1
            continue
        # 收拢本词条的续行：直到下一个词条首行或分隔线为止
        j = i + 1
        body: list[str] = []
        while (
            j < len(lines)
            and not _TXT_ENTRY_RE.match(lines[j])
            and not _RULE_RE.match(lines[j])
            and not _HEAVY_RE.match(lines[j])
        ):
            body.append(lines[j])
            j += 1
        _collect(result, seen, match.group(1), i + 1, _txt_notes(body))
        i = j
    return result


def _txt_notes(body: list[str]) -> str:
    """取出块里的「注」内容。续行缩进 8 格，中间的空行是有意分段。"""
    start = None
    for i, line in enumerate(body):
        if _TXT_NOTE_RE.match(line):
            start = i
            break
    if start is None:
        return ""
    # 「    注  」前缀正好 7 个字符（4 空格 + 注 + 2 空格）
    out = [body[start][7:].rstrip()]
    for line in body[start + 1 :]:
        if line.startswith(" " * 8):
            out.append(line[8:].rstrip())
        elif not line.strip():
            out.append("")
        else:
            break
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


# ---------- 解析：本程序导出的 Markdown ----------


def _parse_markdown_export(text: str) -> ParseResult:
    """按 `## N. 单词` 标题行解析，并还原备注。"""
    lines = text.splitlines()
    result = ParseResult(source_format="Quill Markdown 导出", total_lines=len(lines))
    seen: dict[str, int] = {}

    i = 0
    while i < len(lines):
        match = _MD_ENTRY_RE.match(lines[i])
        if not match:
            i += 1
            continue
        j = i + 1
        body: list[str] = []
        while j < len(lines) and not _MD_ENTRY_RE.match(lines[j]):
            body.append(lines[j])
            j += 1
        _collect(result, seen, match.group(1), i + 1, _md_notes(body))
        i = j
    return result


def _md_unescape(text: str) -> str:
    """还原 `_md_inline` / `_md_note_line` 的转义。

    导出时的转义规则是「在元字符前加一个反斜杠」，因此反转义就是
    「反斜杠 + 任意字符 → 该字符」。两边互为逆运算，用户手写的内容
    能原样回来。
    """
    return re.sub(r"\\(.)", r"\1", text or "")


def _md_notes(body: list[str]) -> str:
    start = None
    for i, line in enumerate(body):
        if _MD_NOTE_RE.match(line):
            start = i
            break
    if start is None:
        return ""
    first = _MD_NOTE_RE.match(body[start])
    out = [_md_unescape(first.group(1))] if first else [""]
    for line in body[start + 1 :]:
        cont = _MD_CONT_RE.match(line)
        if cont:
            out.append(_md_unescape(cont.group(1)))
        elif not line.strip():
            out.append("")
        else:
            break
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


# ---------- 解析：通用生词表 ----------


def parse_word_list(text: str) -> ParseResult:
    """逐行取词，兼收词组。适用于别处整理来的生词表 / 词组表。

    一条行里可能**既有词也有词组**（`happy, take off`），两者各进各的表；
    也有一行就是一条词组（`in charge of`）——那种行以前被整行拒收，理由写作
    「含空格，像是词组不是单词」，用户的词组表因此一条都进不来。

    `skipped` 里除了「整行跳过」，也会出现**行内某一段没能收录**的记录。
    两者都是「用户需要知道自己少收了什么」，放在同一个清单里正是报告要的粒度。
    """
    lines = text.splitlines()
    result = ParseResult(source_format="生词表", total_lines=len(lines))
    seen: dict[str, int] = {}
    seen_phrases: dict[str, int] = {}

    for no, raw in enumerate(lines, start=1):
        line = raw.strip()
        if not line:
            continue
        pick = _words_in_line(line)
        if pick.reason:
            result.skipped.append((no, pick.reason))
            continue
        for note in pick.rejected:
            # 「这一行收下了别的、另有几段没收」同样要说出来：用户看到的是
            # 「这行收下了」，而他那条短语其实没进去，事后无从发现。
            result.skipped.append((no, note))
        if not pick.words and not pick.phrases:
            # 只把「看起来想说点什么」的行记进跳过清单：分割线与空行不算，
            # 否则报告里全是噪音，真正需要用户注意的那几行会被淹没。
            # `rejected` 已逐条说明原因时不再叠一句笼统的「没认出单词」。
            if not pick.rejected and not _DECOR_RE.fullmatch(line):
                result.skipped.append((no, f"没认出单词：{line[:40]}"))
            continue
        for word in pick.words:
            _collect(result, seen, word, no)
        for phrase in pick.phrases:
            _collect_phrase(result, seen_phrases, phrase, no)
    return result


def _is_plain_segment(seg: str) -> bool:
    """一段是不是「若干英文词」——「用分隔符明确列开的纯词表」的判据。

    字符集只允许字母 / 撇号 / 连字符 / 空格（带数字与标点的段说明这一行不是
    纯词表），词数限定在 `1..MAX_WORDS_PER_PHRASE`。

    **词数上限不能取 1，这是本条判据唯一需要解释的地方。** 取 1 时，一行里
    只要夹一条短语（`live to tell`），整条分支就不成立，整行随即被
    `MAX_WORDS_PER_LINE` 判成「像是句子不是词条」——一份 57 段的课程词表因此
    收成 0 个词。上限现在与词组上限同一个数（4），因为超过 4 词的那一段
    既不是词组、也不该让整行作废，判定交给句子阈值。
    """
    if not _PLAIN_SEGMENT_RE.fullmatch(seg):
        return False
    return 1 <= len(_tokens_in(seg)) <= MAX_WORDS_PER_PHRASE


@dataclass
class _LinePick:
    """一行解析出来的东西。

    四个字段的互斥关系由 `_words_in_line` 保证：`reason` 非空表示整行跳过，
    此时其余三项全空；否则 `words` / `phrases` 至少有一项非空，而 `rejected`
    只用来交代「这一行另外那几段为什么没收」。
    """

    words: list[str] = field(default_factory=list)
    phrases: list[str] = field(default_factory=list)
    reason: str = ""
    rejected: list[str] = field(default_factory=list)


def _words_in_line(line: str) -> _LinePick:
    """从一行里取出候选词与候选词组。

    三条分支，按「用户写得有多明确」排：

    1. **用分隔符列开**（`happy, take off`）：段数不限，全取。一段一个词就是
       生词，两个词以上就是词组。这是最明确的一种写法，不设段数上限——否则
       列了 7 个同义词的一行会被当句子丢掉；
    2. **整行是一条纯英文词组**（`in charge of`）：收为词组。这里绝不能退回
       「取第一个词」，那会把 `live to tell` 截成 `live` 写进生词本——写错了
       内容，而那条词条在列表里看着还挺正常，用户很难发现；
    3. **其余情况取第一个词**（`apple 苹果`、`1. ubiquitous /…/ adj.`）。

    超过 `MAX_WORDS_PER_PHRASE` 词的纯英文行不是词组，也不是词表，按句子跳过
    并说明词数——用户才知道该把它删掉还是拆开。
    """
    s = line
    # 行首的编号与项目符号：不属于词本身，但会影响「第一个词是哪段」
    s = _ORDERED_RE.sub("", s)
    s = _PAREN_NUM_RE.sub("", s)
    s = _BULLET_RE.sub("", s)
    # 音标与括号里的内容（音标、词性说明、补充注释）
    s = _PHONETIC_RE.sub(" ", s)
    s = _BRACKET_RE.sub(" ", s)
    # 第一个汉字或中文标点之后都是解释，不是词
    cut = len(s)
    for pattern in (_CJK_RE, _ZH_PUNCT_RE):
        found = pattern.search(s)
        if found:
            cut = min(cut, found.start())
    s = s[:cut]
    if not s.strip():
        return _LinePick()

    tokens = _tokens_in(s)
    if not tokens:
        return _LinePick()

    segments = [seg.strip() for seg in _SPLIT_RE.split(s) if seg.strip()]
    listed = len(segments) > 1 and all(_is_plain_segment(seg) for seg in segments)
    # 这条阈值必须在「列开的纯词表」判断**之后**：列了 7 段的一行按段收，
    # 不受句子阈值限制。
    if not listed and len(tokens) > MAX_WORDS_PER_LINE:
        return _LinePick(reason=f"一行有 {len(tokens)} 个词，像是句子不是词条")

    if listed:
        return _finalize(
            [seg for seg in segments if len(_tokens_in(seg)) == 1],
            [seg for seg in segments if len(_tokens_in(seg)) > 1],
            line,
        )

    flat = s.strip()
    if len(tokens) > 1 and _PLAIN_SEGMENT_RE.fullmatch(flat):
        if len(tokens) <= MAX_WORDS_PER_PHRASE:
            return _LinePick(phrases=[" ".join(flat.split())])
        return _LinePick(
            reason=(
                f"这一行有 {len(tokens)} 个词，超过词组的 "
                f"{MAX_WORDS_PER_PHRASE} 词上限，像是句子，未收录"
            )
        )
    return _finalize([tokens[0]], [], line)


def _finalize(words: list[str], phrases: list[str], line: str) -> _LinePick:
    """把候选分成「能收的词 / 能收的词组 / 要报告的段」，并在全空时给出原因。

    词的校验与词组的校验**各用各的判据**（`_valid_word` / `_valid_phrase`），
    不合并成一个：词的合法性（长度、字符集）与词组的合法性（词数区间）是两件
    事，合成一条就意味着放宽词组时要连带动词的判据。
    """
    kept_words: list[str] = []
    kept_phrases: list[str] = []
    rejected: list[str] = []
    for pick in words:
        if pick.lower() in _POS_MARKERS:
            continue
        # **判据前先归一化**：`Apple` 与 `apple` 是同一个词，而 `_WORD_RE` 只认
        # 小写形态——少了这一步，大小写混排的词表会把每个大写行都报成「不是单词」
        # （`_collect` 那边本来就会先 normalize，这里必须与它同一口径）。
        if _valid_word(normalize(pick)):
            kept_words.append(pick)
        else:
            rejected.append(pick)
    for pick in phrases:
        if _valid_phrase(pick):
            kept_phrases.append(" ".join(pick.split()))
        else:
            rejected.append(pick)

    if not kept_words and not kept_phrases:
        if rejected:
            # 整行都收不下：让逐条说明来交代，不再叠一句笼统的「没认出单词」。
            return _LinePick(rejected=[_reject_note(seg) for seg in rejected])
        # 有「词」但一个都收不下（只有词性标记、整行都是被剥掉的括号内容）。
        # 不能说成「空行」轻轻放过——用户会以为这行本来就没事。
        return _LinePick(reason=f"没认出可收录的单词：{line[:40]}")
    return _LinePick(
        words=kept_words,
        phrases=kept_phrases,
        rejected=[_reject_note(seg) for seg in rejected],
    )


def _valid_phrase(text: str) -> bool:
    """一条词组是否可收录：字符集合法，词数在 `MIN..MAX_WORDS_PER_PHRASE` 之间。

    字符集用的是与「纯词表的一段」同一份 `_PLAIN_SEGMENT_RE`——词组里出现
    数字或标点（`3.0 version`、`word,`）说明这不是用户想收的搭配。
    """
    if not _PLAIN_SEGMENT_RE.fullmatch(text):
        return False
    return MIN_WORDS_PER_PHRASE <= len(_tokens_in(text)) <= MAX_WORDS_PER_PHRASE


def _collect_phrase(
    result: ParseResult, seen: dict[str, int], raw: str, line_no: int
) -> bool:
    """收下一条词组：折叠空白、查重、按词组身份放进 `words`。

    查重用**独立的一张表**（`seen` 由调用方分开传），与单词那边不共用：同一个
    `seen` 字典会让 `take off` 与某个词共用一个键空间，而它们进的是两张表，
    「重复」在两边是不同的意思。词组按小写判重，与 `phrases` 表上的
    `COLLATE NOCASE` 同一口径——否则 `Take Off` 与 `take off` 在文件里算两条，
    进了库却撞唯一约束，后一条会被静默丢弃。
    """
    phrase = " ".join((raw or "").split())
    if not _valid_phrase(phrase):
        return False
    key = phrase.lower()
    if key in seen:
        result.duplicates += 1
        return False
    seen[key] = line_no
    result.words.append(ParsedWord(word=phrase, line=line_no, kind=KIND_PHRASE))
    return True


def _reject_note(seg: str) -> str:
    """一句能让用户照着改的说明。词数越界与「过短」是两种完全不同的毛病。"""
    text = seg.strip()
    count = len(_tokens_in(text))
    if " " in text and count > MAX_WORDS_PER_PHRASE:
        return f"「{text}」有 {count} 个词，超过词组的 {MAX_WORDS_PER_PHRASE} 词上限，未收录"
    if " " in text:
        return f"「{text}」不是可收录的词组（含数字或标点？），未收录"
    return f"「{text}」太短或不是单词，未收录"


def _tokens_in(text: str) -> list[str]:
    """取出英文词。

    **这里曾经多写了一道「贴着数字就整段丢弃」的检查，那是个过度抑制的
    缺陷。** 它的本意是挡住 `word2` 这类噪音，实际连 `apple1`、`banana2`、
    `cherry3` 一起挡掉了——而「词尾紧跟序号」是别处导出的词表里最常见的
    格式之一，整份词表会被收成 0 个词，用户只看到一屏「跳过行」。

    根因是**同一个属性有两份定义**：`_WORD_RE` 里已经有一道防线（它的
    字符集里根本没有数字），此处再判一次不但多余，还比它更狠——一份正确、
    一份过度，结果由过度的那份说了算。现在只留 `_valid_word` 一处裁决：
    `h2o` 这类中间夹数字的形态它照样挡住，而 `apple1` 匹配出的本就是
    `apple`（`_TOKEN_RE` 不含数字），正常收下。
    """
    return [match.group() for match in _TOKEN_RE.finditer(text)]


def _collect(
    result: ParseResult,
    seen: dict[str, int],
    raw: str,
    line_no: int,
    notes: str = "",
    fill: dict | None = None,
) -> bool:
    """规整、查重并收下一个候选词。返回是否真的收下了。

    `fill` 原样带到候选词上，**这里不校验键名**——白名单在写入侧
    （`run_import`）统一裁决，免得每种解析器各过滤一遍、口径还不一致。
    """
    word = normalize(raw)
    if not _valid_word(word):
        return False
    if word in seen:
        result.duplicates += 1
        return False
    seen[word] = line_no
    result.words.append(
        ParsedWord(word=word, line=line_no, notes=notes, fill=dict(fill or {}))
    )
    return True


def _valid_word(word: str) -> bool:
    if len(word) < MIN_WORD_LEN or not word.isascii():
        return False
    # normalize() 只对小写化纯字母词做处理，带数字的形态会原样留下，
    # 这里用字符集把它挡在外面（「word2」这类不是要收录的词）。
    return bool(_WORD_RE.fullmatch(word))


# ---------- 执行导入 ----------


def run_import(
    service,
    repo: Repository,
    words: list[ParsedWord],
    *,
    known: set[int] | None = None,
    on_progress=None,
    is_cancelled=None,
) -> ImportOutcome:
    """逐个查询并入库，返回分类结果。

    两种候选走两条路：`KIND_WORD` 走 `service.lookup`（写 entries），
    `KIND_PHRASE` 走 `service.lookup_phrase`（写 phrases）。分派在这一层做，
    因为解析器只负责判断「这条东西是什么」，不该知道库里长什么样。

    **「新增」与「已存在」靠 id 快照判定**，不看 `lookup()` 的第二个返回值：
    那个只说明「是否命中缓存」，而别名命中（running → 已有词条 run）同样
    算缓存命中——把这种说成「新增」会让报告里的数字虚高，用户按它对不上账。
    词组那条路用的是 `lookup_phrase` 自己给的「本次是否新增」，它按收藏条数
    有没有涨来判，判据只有那一处。

    `known` 允许外部传入同一个 set 跨批次累积，这样分块导入时每块不必
    重新扫一遍全库的 id。**词组 id 不进这个集合**：它是 entries 的 id 空间，
    两张表各自从 1 发号，把词组的 3 号混进去，一个同样叫 3 号的词条就会被
    当成「已存在」直接跳过——库里明明没有，报告却说有。
    """
    if known is None:
        known = repo.all_ids()
    outcome = ImportOutcome()
    total = len(words)

    for index, item in enumerate(words, start=1):
        if is_cancelled is not None and is_cancelled():
            outcome.cancelled = True
            break
        if on_progress is not None:
            on_progress(index, total, item.word)

        if item.kind == KIND_PHRASE:
            _import_phrase(service, item, outcome)
            continue

        entry = _lookup_word(service, item, outcome)
        if entry is None:
            continue
        if entry.id in known:
            outcome.existing.append(item.word)
            continue

        known.add(entry.id)
        outcome.added.append(entry.lemma)
        _apply_file_fields(repo, item, entry, outcome)
    return outcome


def _import_phrase(service, item: ParsedWord, outcome: ImportOutcome) -> None:
    """词组走 `lookup_phrase`，成败都记进 outcome。

    新增与否取它自己给的返回值，不走 id 快照：词组的 id 属于另一张表，
    与 `known` 那份 entries id 集合不可混用。
    """
    try:
        phrase, created = service.lookup_phrase(item.word)
    except Exception as exc:  # noqa: BLE001 - 一条失败不该中断整批
        outcome.failed.append((item.word, str(exc) or exc.__class__.__name__))
        return
    if phrase is None or phrase.id is None:
        outcome.failed.append((item.word, "查询没有返回词组"))
        return
    (outcome.phrases_added if created else outcome.phrases_existing).append(
        phrase.phrase
    )


def _lookup_word(service, item: ParsedWord, outcome: ImportOutcome):
    """查询单个词条。异常与空结果都记进 outcome，并返回 None 让调用方跳过。"""
    try:
        entry, _cached = service.lookup(item.word)
    except Exception as exc:  # noqa: BLE001 - 一个词失败不该中断整批导入
        outcome.failed.append((item.word, str(exc) or exc.__class__.__name__))
        return None
    if entry is None or entry.id is None:
        outcome.failed.append((item.word, "查询没有返回词条"))
        return None
    return entry


def _apply_file_fields(
    repo: Repository, item: ParsedWord, entry: Entry, outcome: ImportOutcome
) -> None:
    """把源文件里的备注与结构化字段补进词条，有内容才落库。

    源文件里带备注或结构化字段（本程序导出的文件带备注，有道 XML 带释义
    与音标）时补进去。

    这里**不需要**再判一次「字段是否已有内容」——能走到这一行的都是本次
    新增的词条（已有的在调用方 `continue` 掉了）。新建行的字段由 lookup 填过，
    但那属于**程序生成的内容**、不是用户数据：用文件里的值覆盖它，正是
    「导入」的本意（用户要的就是文件里那份释义）。
    这里曾经多写了一个 `not (entry.notes or "").strip()` 条件，它恒为真：
    看着多守了一道，实际一个字节都没守住，还会让人以为「导入不覆盖备注」
    这件事是在这条路径上被挡住的。变异测试就是靠「把它破坏掉却没有任何
    测试报警」把这一点暴露出来的。
    真正管住「不覆盖用户数据」的是调用方那条 `entry.id in known` 分支，
    以及 upsert 里对 notes / tags 的保留逻辑。
    """
    if not (item.notes or item.fill):
        return
    if item.notes:
        entry.notes = item.notes
        outcome.notes_restored += 1
    for name, value in (item.fill or {}).items():
        # **白名单在写入侧统一裁决**：解析侧只负责产出，将来新增一种
        # 解析器时不会因为忘了过滤，就把 source 这类程序元数据写进库。
        if name in _FILLABLE_FIELDS and value:
            setattr(entry, name, value)
    repo.upsert(entry)
