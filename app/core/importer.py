"""生词表导入：把一份文本变成生词本里的词条。

## 为什么要走两条解析路径

用户给的 txt 通常有两种出身：

**一、本程序自己导出的**（`export_text` / `export_markdown` 的产物）。
这种文件的每条词条占**多行**——「英 / 中 / 例 / 同 / 注」各占一行。
若按「每行取第一个词」处理，那些续行会被当成词条：`seeming`、`becoming`
之类从释义里被挖出来收进生词本。这不是「少收了几个词」，是往用户的
数据里**写入错误内容**，而且一条词条能带出三五个假词。所以必须先认出
这种格式，按块解析——只有「N. 单词」那一行才是词条。

**二、别处整理来的生词表**（一行一个或几个词，可能带编号、音标、中文释义）。
这类没有固定结构，只能按行取词。

**三、本程序导出的 JSON**（`export_json` 的产物）。这是带**结构**的格式，
所以它不需要「猜」——顶层写着 `format: quill-entries`。但它必须被认出来，
否则普通词表解析器会把 `"lemma"`、`"phonetic"` 这些**字段名**当成单词收进
生词本：实测一个 2 条词条的 JSON 会产出 16 个假词条，全是字段名。

**四、别的应用导出的 XML**，目前认的是有道单词本的格式
（`<wordbook><item><word>…`）。它的标签名恰好都是合法英文词，落到通用词表
解析器上会产出 8 个假词条（xml / wordbook / item / word / trans / phonetic /
tags / progress），而真词一个都取不到、跳过清单还是空的——用户看到「导入
成功 8 个词」，库里装的全是标签名。

**五、Word 文档（`.docx`）**：正文由 `read_docx_text()` 解包成纯文本，再回到
上面四条路径去分派——所以它不算「第五条解析路径」，而是**读取层**多了一种来源。
只取 `word/document.xml`：页眉与脚注在同目录的其它 part 里，一起读进来会让
页眉上的公司名变成生词。

四条路径由 `parse_text()` 按文件指纹分派。**判错的方向是不对称的**：
把普通词表误判成导出格式只会漏收（用户看得见、能重来），
把导出格式误判成普通词表会写入假词（污染数据、且不易察觉）。
因此指纹倾向于「像就认」，并且必要的条件要同时满足——普通词表不会同时
具备 72 个 `=` 的头部线和 72 个 `-` 的分隔线，也不会以 `{` 开头且带我们的
格式标识，更不会以 `<?xml` 开头且根元素是 `wordbook`。
"""

