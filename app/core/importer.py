@dataclass
class ParsedWord:
    """一个候选词（或一条候选词组）。

    `notes` 与 `fill` 只在解析**带结构的**文件（本程序导出的文本 / Markdown /
    JSON、有道单词本的 XML）时才有内容：

    - `notes` 是备注，还原到 `Entry.notes`；
    - `fill` 是**可回填的字段**（释义、音标、分类等），键名必须在
      `_FILLABLE_FIELDS` 白名单里。用字典而不是给每个可回填字段开一个属性，
      是为了新增字段时不必再动这个类，且写入侧能一次校验完。

    `kind` 决定这条东西**写进哪张表**。生词本与词组收藏是两张各自从 1 发号的
    表，把 `take off` 当词条写进去会得到一条 lemma 里带空格的怪词条；反之把
    `apple` 当词组写进去，词组收藏里就多一条与生词本重复的行。所以这个字段
    不是分类标签，是**路由**，由解析器判定、由 `run_import` 消费，界面不猜。
    """

    word: str
    line: int
    notes: str = ""
    fill: dict = field(default_factory=dict)
    kind: str = KIND_WORD


@dataclass
class ParseResult:
    words: list[ParsedWord] = field(default_factory=list)
    duplicates: int = 0
    skipped: list[tuple[int, str]] = field(default_factory=list)
    total_lines: int = 0
    source_format: str = "生词表"

    @property
    def count(self) -> int:
        return len(self.words)

    @property
    def phrase_count(self) -> int:
        """其中有几条是词组。报告要把两类分开说，否则用户看到「认出 12 个」
        却只多出 9 条生词，会以为漏收了 3 个。"""
        return sum(1 for item in self.words if item.kind == KIND_PHRASE)

    @property
    def word_count(self) -> int:
        return self.count - self.phrase_count

    def preview(self, limit: int = 8) -> str:
        """给用户核对识别结果用的前几个词。"""
        shown = [w.word for w in self.words[:limit]]
        text = "、".join(shown)
        if self.count > limit:
            text += f" …（共 {self.count} 个）"
        return text


@dataclass
class ImportOutcome:
    """一次导入的分类结果。

    词条与词组**分开统计**：它们进的是两张表，「新增 5 条」在用户眼里是
    「生词本多了 5 条」，把词组混进同一个数字，他一对账就发现对不上——
    而实际上一条都没漏。
    """

    added: list[str] = field(default_factory=list)
    existing: list[str] = field(default_factory=list)
    failed: list[tuple[str, str]] = field(default_factory=list)
    phrases_added: list[str] = field(default_factory=list)
    phrases_existing: list[str] = field(default_factory=list)
    notes_restored: int = 0
    cancelled: bool = False

    @property
    def handled(self) -> int:
        return (
            len(self.added)
            + len(self.existing)
            + len(self.phrases_added)
            + len(self.phrases_existing)
            + len(self.failed)
        )

    def merge(self, other: "ImportOutcome") -> None:
        self.added.extend(other.added)
        self.existing.extend(other.existing)
        self.failed.extend(other.failed)
        self.phrases_added.extend(other.phrases_added)
        self.phrases_existing.extend(other.phrases_existing)
        self.notes_restored += other.notes_restored
        self.cancelled = self.cancelled or other.cancelled


# 用户**直接输入**时的分隔符：空白、逗号、分号、换行、顿号。
#
# 刻意不复用标签那套分隔符（models._TAG_SEP_RE）：那边允许用空格分隔（「考研
# 高频」是两个标签），而这里空格就是词的边界（「hello world」是两个词）。两处
# 长得像，语义相反，共用一个规则会把它们一起搞错。
_INPUT_SPLIT_RE = re.compile(r"[\s,;、，；]+")


def split_words(text: str) -> list[str]:
    """把用户直接输入的一串文本拆成候选词（输入框批量查词用）。

    **只做拆分与规整，不判断「这是不是一个多词输入」**——那是调用方的语义：
    它还要先试一次整串（`ice cream` 是一个词），未命中才用这里的结果。把那个
    判断塞进来，会让本函数既要访问缓存又要访问输入框。

    每个词都过 `_valid_word`（与文件导入**同一套**判据）。这件事必须由本函数
    承担：输入框与导入对「什么算一个可收录的词」若各判一套，同一个词从输入框
    进得来、从文件进不来，而两边都不会报错。
    """
    out: list[str] = []
    for chunk in _INPUT_SPLIT_RE.split(str(text or "")):
        word = normalize(chunk)
        if _valid_word(word) and word not in out:
            out.append(word)
    return out


# ---------- 读文件 ----------


def read_text_file(path: Path | str) -> str:
    """读文本，逐种编码尝试。**不会抛 UnicodeDecodeError**。

    编码这件事必须容错：Windows 上「记事本另存为 ANKI 词表」得到的是
    GBK，而别处下载的又是带 BOM 的 UTF-8。报一句「无法读取」等于把
    用户的文件判了死刑，而它其实好好的。
    """
    path = Path(path)
    size = path.stat().st_size
    if size > MAX_FILE_BYTES:
        raise ValueError(
            f"文件过大（{size / 1024 / 1024:.1f} MB）。生词表通常只有几十 KB，"
            "请确认选对了文件。"
        )
    raw = path.read_bytes()
    # 带 BOM 的 UTF-16 要先认出来：gb18030 几乎能解码任意字节序列，
    # 若让它先试，UTF-16 文件会被「成功」解成一片乱码。
    #
    # 这里必须包 try —— 本函数承诺「不会抛 UnicodeDecodeError」，而只有 BOM
    # 正确、正文损坏的文件（字节数为奇数、或含孤立代理对）会让 decode 抛错。
    # 不包的话这个异常会绕过下面的容错循环直接冒出来，承诺就成了空话。
    # 失败时**落回**通用循环，让 gb18030 / 替换字符那两级去兜。
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        try:
            return raw.decode("utf-16")
        except UnicodeDecodeError:
            pass
    for encoding in _ENCODINGS:
        try:
            return raw.decode(encoding)
        except (UnicodeDecodeError, LookupError):
            continue
    # 全试不通时不给死路：用替换字符读出来，用户至少能看到哪一段乱了，
    # 好过「无法读取」四个字。
    return raw.decode("utf-8", errors="replace")


